def join_a_string_several_times(string, times):
    """
    This function takes a string and an integer as input and returns the string repeated 'times' number of times.
    
    :param string: The string to be repeated
    :param times: The number of times to repeat the string
    :return: The concatenated string
    """
    return string * times

print(join_a_string_several_times("Hello", 3))









